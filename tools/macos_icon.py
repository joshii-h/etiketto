#!/usr/bin/env python3
"""Write data/icons/tavletta-macos.svg from the main icon.

    python3 tools/macos_icon.py          write it
    python3 tools/macos_icon.py --check  exit 1 if it is out of date

The macOS icon (Big Sur style) is the tablet of data/xyz.joshuahirsig.Tavletta.svg
on an 824 x 824 plate centred in 1024 x 1024: a rounded square with
continuous corners (each corner a superellipse quarter over 1.528 times the
radius, as Apple's smoothed corners), light grey to white. The soft shadows
of plate and tablet are layered shapes with a low fill-opacity, not SVG
filters, so QtSvg and other SVG Tiny 1.2 renderers draw them too.

Generated, so it cannot drift from the main icon: tests/test_icons.py
checks that the file is what this script writes. Only the standard library.
"""

from __future__ import annotations

import math
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MAIN = ROOT / "data" / "xyz.joshuahirsig.Tavletta.svg"
OUT = ROOT / "data" / "icons" / "tavletta-macos.svg"

CANVAS = 1024
PLATE = 824  # Apple's icon grid: the plate, centred
RADIUS = 185.0  # of the plate's corners
SCALE = 5.75  # the 128 px tablet on the plate
# the tablet's frame in the main icon (x, y of the base, width, height, radius)
FRAME = (8, 26, 112, 86, 12)


def squircle(x0: float, y0: float, size: float, r: float, n: float = 3.2, steps: int = 24) -> str:
    """Path data of a rounded square with continuous corners."""
    extent = min(1.528 * r, size / 2)
    x1, y1 = x0 + size, y0 + size
    points = []
    corners = (
        (x1 - extent, y1 - extent, 1, 1, 0),
        (x0 + extent, y1 - extent, -1, 1, 90),
        (x0 + extent, y0 + extent, -1, -1, 180),
        (x1 - extent, y0 + extent, 1, -1, 270),
    )
    for cx, cy, sx, sy, start in corners:
        for i in range(steps + 1):
            t = math.radians(start + 90 * i / steps)
            c, s = abs(math.cos(t)), abs(math.sin(t))
            points.append((cx + sx * c ** (2 / n) * extent, cy + sy * s ** (2 / n) * extent))
    d = "M" + " ".join("%.1f %.1f" % p for p in points) + "z"
    return re.sub(r"\.0(?=[ z])", "", d)


def svg() -> str:
    main = MAIN.read_text(encoding="utf-8")
    gradients = re.search(r"<defs>\n(.*?)\s*</defs>", main, re.S)
    assert gradients, "the main icon has no <defs>"
    shapes = main.split("</defs>", 1)[1].replace("</svg>", "")
    body = "\n".join("    " + line.strip() for line in shapes.splitlines() if line.strip())
    offset = (CANVAS - PLATE) / 2
    plate_shadow = [
        '  <path d="%s" fill="#000000" fill-opacity="0.016"/>'
        % squircle(offset - 2 * i, offset - 2 * i + 10, PLATE + 4 * i, RADIUS + 2 * i)
        for i in range(12, 0, -1)
    ]
    tx, ty = CANVAS / 2 - 64 * SCALE, CANVAS / 2 - 66 * SCALE - 6
    fx, fy, fw, fh, fr = FRAME
    tablet_shadow = []
    for i in range(10, 0, -1):
        grow = 2.4 * i
        tablet_shadow.append(
            '  <rect x="%.1f" y="%.1f" width="%.1f" height="%.1f" rx="%.1f"'
            ' fill="#000000" fill-opacity="0.028"/>'
            % (
                tx + fx * SCALE - grow,
                ty + fy * SCALE - grow + 12,
                fw * SCALE + 2 * grow,
                fh * SCALE + 2 * grow,
                fr * SCALE + grow,
            )
        )
    nl = "\n"
    return f"""<svg xmlns="http://www.w3.org/2000/svg" width="{CANVAS}" height="{CANVAS}" viewBox="0 0 {CANVAS} {CANVAS}">
  <!-- Tavletta for macOS (Big Sur style): the tablet on an 824 x 824 plate
       (rounded square with continuous corners) centred in 1024 x 1024.
       The soft shadows are layered shapes with low opacity, not SVG
       filters. Generated by tools/macos_icon.py from the main icon
       (data/xyz.joshuahirsig.Tavletta.svg): do not edit, run the script. -->
  <defs>
{gradients.group(1)}
    <linearGradient id="plate" x1="0" y1="{offset:g}" x2="0" y2="{offset + PLATE:g}" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="#ffffff"/>
      <stop offset="1" stop-color="#deddda"/>
    </linearGradient>
  </defs>
  <!-- plate shadow -->
{nl.join(plate_shadow)}
  <!-- plate -->
  <path d="{squircle(offset, offset, PLATE, RADIUS)}" fill="url(#plate)"/>
  <!-- tablet shadow -->
{nl.join(tablet_shadow)}
  <!-- the tablet: the main icon, scaled -->
  <g transform="translate({tx:g} {ty:g}) scale({SCALE:g})">
{body}
  </g>
</svg>
"""


def main(argv: list[str]) -> int:
    text = svg()
    if "--check" in argv[1:]:
        if OUT.read_text(encoding="utf-8") != text:
            print("%s is out of date: run tools/macos_icon.py" % OUT, file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
